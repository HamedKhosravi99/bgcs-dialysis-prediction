"""Write outputs/RESULTS_SUMMARY.md, a readable summary of the analysis outputs."""
import json
import os

import numpy as np
import pandas as pd

from common import OUT

AN = os.path.join(OUT, "analysis")
ORDER = ["No augmentation", "SMOTE", "CTGAN", "Gaussian Copula", "BGCS stage 1 (no LLM)", "BGCS"]
CLFS = ["DT", "RF", "SVM", "LR"]


def md_table(df):
    cols = list(df.columns)
    lines = ["| " + " | ".join(str(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]) for c in cols) + " |")
    return "\n".join(lines)


def ordered(df):
    df = df.copy()
    df["_m"] = df["method"].map({m: i for i, m in enumerate(ORDER)})
    df["_c"] = df["classifier"].map({c: i for i, c in enumerate(CLFS)})
    return df.sort_values(["_m", "_c"]).drop(columns=["_m", "_c"])


def main():
    full = ordered(pd.read_csv(os.path.join(AN, "table_full_metrics.csv")))
    boot = pd.read_csv(os.path.join(AN, "table_bootstrap_ci.csv"))
    tests = pd.read_csv(os.path.join(AN, "table_paired_tests.csv"))
    binom = pd.read_csv(os.path.join(AN, "table_binomial_multiplicity.csv"))
    orig = pd.read_csv(os.path.join(AN, "table_original_recall_ci.csv"))
    thr = pd.read_csv(os.path.join(AN, "table_thresholds.csv"))
    out = ["# Results summary", "",
           "Generated by `summarize.py` from `outputs/analysis/`. Medians are across 25 runs (no augmentation: 1 deterministic run); "
           "95% CIs are from a stratified bootstrap of the 866 test patients (40 with dialysis), with the median taken over runs in each resample.", ""]

    # ---- GPT-2 screening model and ablation
    out += ["## GPT-2 screening model and ablation", ""]
    vpath = os.path.join(OUT, "gpt2", "validation.json")
    fpath = os.path.join(OUT, "gpt2", "finetune_info.json")
    if os.path.exists(vpath):
        v = json.load(open(vpath))
        rows = []
        for split in ["test", "train"]:
            d = v[split]
            rows.append({"split": "held-out 20%" if split == "test" else "training 80%", "n (dialysis)": f"{d['n']} ({d['positives']})",
                         "AUROC": f"{d['auroc']:.3f}", "AUPRC": f"{d['auprc']:.3f}",
                         "sensitivity@0.5": f"{d['sensitivity']:.3f}", "specificity@0.5": f"{d['specificity']:.3f}",
                         "predicted dialysis": d["TP"] + d["FP"]})
        out += [f"Checkpoint used for screening: `{v['checkpoint']}`.", "", md_table(pd.DataFrame(rows)), ""]
    if os.path.exists(fpath):
        f = json.load(open(fpath))
        ev = [h for h in f["log_history"] if "eval_loss" in h]
        L = f["serialized_length_tokens_sample200"]
        out += [f"Fine-tuning: {f['train_rows']} training records, {f['train_seconds'] / 60:.1f} min on {f['device']} ({f['machine']}). "
                f"Eval loss by epoch: " + ", ".join(f"{h['eval_loss']:.3f}" for h in ev) + ". "
                f"Serialized length (200 training records): median {L['median']:.0f} tokens (range {L['min']}–{L['max']}); "
                f"{L['share_over_512']:.0%} exceed 512 tokens.", ""]
    abl = full[full.method.isin(["Gaussian Copula", "BGCS stage 1 (no LLM)", "BGCS"])]
    out += ["Ablation (median [IQR] over 25 runs):", "",
            md_table(abl[["method", "classifier", "n_synthetic_median", "recall", "specificity", "precision", "auroc", "auprc"]]), ""]

    # ---- uncertainty and paired tests
    out += ["## Confidence intervals, paired tests, multiplicity", "", "Recall (Table 3 layout, re-run):", ""]
    rec = full[["method", "classifier", "recall_median", "recall_min", "recall_max"]].merge(
        boot[["method", "classifier", "recall_ci"]], on=["method", "classifier"])
    rec["median"] = rec["recall_median"].map(lambda x: f"{x:.3f}")
    rec["range"] = [f"{a:.3f}–{b:.3f}" for a, b in zip(rec.recall_min, rec.recall_max)]
    out += [md_table(ordered(rec)[["method", "classifier", "median", "range", "recall_ci"]].rename(columns={"recall_ci": "95% CI"})), ""]
    out += ["Per-run recalls saved in notebook 01 (the values behind Table 3), with CIs:", "",
            md_table(orig[["method", "classifier", "median", "range", "median_ci_over_runs", "wilson_ci_test_set_40_dialysis"]]), ""]
    ref = tests["comparison"].iloc[0].split(" vs ")[0]
    w = tests[tests.test.str.startswith("Wilcoxon") & tests.metric.isin(["recall", "auroc", "auprc", "specificity", "precision"])].copy()
    w["result"] = [f"{d:+.3f} (p={p:.3g}; Holm {ph:.3g})" for d, p, ph in zip(w.difference_in_medians, w.p_raw, w.p_holm)]
    piv = w.pivot_table(index=["metric", "comparison"], columns="classifier", values="result", aggfunc="first")[CLFS].reset_index()
    out += [f"Wilcoxon signed-rank, {ref} minus comparator (difference in medians; raw and Holm-adjusted p):", "", md_table(piv), ""]
    fr = tests[tests.test.str.startswith("Wilcoxon")].groupby(["metric", "classifier"])["friedman_p_all_methods"].first().unstack()[CLFS]
    fr = fr.loc[[m for m in ["recall", "specificity", "precision", "f1", "auroc", "auprc"] if m in fr.index]].reset_index()
    out += ["Friedman test across all methods (p):", "", md_table(fr.round(4)), ""]
    pt = tests[~tests.test.str.startswith("Wilcoxon")].copy()
    pt["result"] = [f"{d:+.3f} p={p:.3g} (Holm {ph:.3g})" if "DeLong" in t else f"{int(d):+d} pts p={p:.3g} (Holm {ph:.3g})"
                    for t, d, p, ph in zip(pt.test, pt.difference_in_medians, pt.p_raw, pt.p_holm)]
    piv2 = pt.pivot_table(index=["test", "comparison"], columns="classifier", values="result", aggfunc="first")[CLFS].reset_index()
    out += ["Patient-level paired tests on the shared test set (DeLong on run-averaged scores; exact McNemar on majority votes; "
            "for McNemar, 'pts' = patients the reference detects minus patients the comparator detects among dialysis patients, "
            "or false alerts avoided among non-dialysis patients):", "", md_table(piv2), ""]
    out += ["Feature-wise binomial tests (real dialysis records vs synthetic, 159 features; medians over 25 runs):", "",
            md_table(binom.round(3)), ""]

    # ---- full metrics
    out += ["## Full metrics, calibration, thresholds", "",
            md_table(full[["method", "classifier", "recall", "specificity", "precision", "npv", "f1", "auroc", "auprc"]]), "",
            md_table(full[["method", "classifier", "balanced_accuracy", "mcc", "brier", "cal_slope", "cal_intercept", "ece", "oe_ratio"]]), "",
            "oe_ratio = observed prevalence (4.6%) / mean predicted probability; values < 1 mean predicted risks are too high. "
            "Calibration slope/intercept are not estimable for the decision tree (leaf probabilities are 0 or 1).", ""]
    sub = thr[thr.threshold.isin([0.1, 0.3, 0.5]) & thr.classifier.isin(["DT", "LR"])].copy()
    sub = sub.round(3)
    out += ["Operating points at fixed probability thresholds (DT and LR; medians over runs; full table in table_thresholds.csv):", "",
            md_table(ordered(sub)[["method", "classifier", "threshold", "sensitivity", "specificity", "ppv", "npv", "flagged_fraction"]]), ""]
    nbrows = []
    for m in ["real", "smote", "ctgan", "gc", "binary_copula", "bgcs"]:
        p = os.path.join(OUT, m, "predictions.npz")
        if not os.path.exists(p):
            continue
        z = np.load(p)
        t = z["dca_thresholds"]
        for c, cl in zip(["DecisionTree", "RandomForest", "SVM", "LogisticRegression"], CLFS):
            nb = np.median(z[f"{c}__net_benefit"], axis=0)
            row = {"method": {"real": "No augmentation", "smote": "SMOTE", "ctgan": "CTGAN", "gc": "Gaussian Copula",
                              "binary_copula": "BGCS stage 1 (no LLM)", "bgcs": "BGCS"}[m], "classifier": cl}
            for th in [0.05, 0.1, 0.2, 0.3]:
                row[f"NB@{th}"] = f"{nb[np.argmin(abs(t - th))]:.4f}"
            nbrows.append(row)
    if nbrows:
        y = np.load(os.path.join(OUT, "real", "predictions.npz"))["y_test"]
        prev = y.mean()
        treat_all = {th: prev - (1 - prev) * th / (1 - th) for th in [0.05, 0.1, 0.2, 0.3]}
        out += ["Decision curve: net benefit (median over runs) at selected thresholds. Treat-all: " +
                ", ".join(f"{k}: {v:.4f}" for k, v in treat_all.items()) + "; treat-none: 0.", "",
                md_table(ordered(pd.DataFrame(nbrows))), ""]

    # ---- screening efficiency
    eff_p = os.path.join(AN, "table_filter_efficiency.csv")
    out += ["## Screening-step efficiency and compute", ""]
    if os.path.exists(eff_p):
        out += [md_table(pd.read_csv(eff_p).round(3)), ""]
    for m in ["binary_copula", "smote", "gc", "ctgan"]:
        tp = os.path.join(OUT, m, "timing.json")
        if os.path.exists(tp):
            t = json.load(open(tp))
            g = t["per_run_generation_seconds"]
            out.append(f"- {m}: generation {np.mean(g):.2f} s/run (mean)" +
                       (f", generator fit {t['generator_fit_seconds']:.1f} s" if t.get("generator_fit_seconds") else "") +
                       f"; total {t['total_seconds'] / 60:.1f} min for {t['n_runs']} runs including classifiers")
    out.append("")

    # ---- Fig 6
    info = os.path.join(OUT, "figures", "Fig6_tree_info.txt")
    if os.path.exists(info):
        out += ["## Fig 6", "", "`outputs/figures/Fig6_tree_redrawn.tif` (2250 px wide, 300 dpi, 8-pt Arial). " +
                open(info).read().replace("\n", "; "), ""]

    with open(os.path.join(OUT, "RESULTS_SUMMARY.md"), "w") as f:
        f.write("\n".join(out))
    print("wrote", os.path.join(OUT, "RESULTS_SUMMARY.md"))


if __name__ == "__main__":
    main()
